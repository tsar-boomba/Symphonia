/// Layer 1 dequantization factors.
pub fn mp1_factor() -> Vec<f32> {
    let mut factor = vec![0f32; 16];

    for (i, factor) in factor.iter_mut().enumerate().skip(2) {
        let a = 1 << i;
        let b = 1 << (i - 1);

        *factor = (a as f32 / (a - 1) as f32) * (b as f32).recip();
    }

    factor
}

/// x(i) = s(i)^(4/3), for s(i) in 0..8207.
pub fn mp3_pow43() -> Vec<f32> {
    (0..8207).map(|i| libm::powf(i as f32, 4.0 / 3.0)).collect()
}

/// y = 2^(0.25 * (x - 256)), for x in 0..512.
pub fn mp3_pow2() -> Vec<f32> {
    (0..512)
        .map(|i| {
            let exp = i as f32 - 256.0;
            libm::powf(2.0, exp * 0.25)
        })
        .collect()
}

/// IMDCT window coefficients for: Long, Start, Short, and End blocks.
pub fn mp3_imdct_windows() -> [[f32; 36]; 4] {
    const PI_36: f32 = PI / 36.0;
    const PI_12: f32 = PI / 12.0;

    let mut windows = [[0f32; 36]; 4];

    for i in 0..36 {
        windows[0][i] = libm::sinf(PI_36 * (i as f32 + 0.5));
    }

    for i in 0..18 {
        windows[1][i] = libm::sinf(PI_36 * (i as f32 + 0.5));
    }
    for i in 18..24 {
        windows[1][i] = 1.0;
    }
    for i in 24..30 {
        windows[1][i] = libm::sinf(PI_12 * ((i - 18) as f32 + 0.5));
    }

    for i in 0..12 {
        windows[2][i] = libm::sinf(PI_12 * (i as f32 + 0.5));
    }

    for i in 6..12 {
        windows[3][i] = libm::sinf(PI_12 * ((i - 6) as f32 + 0.5));
    }
    for i in 12..18 {
        windows[3][i] = 1.0;
    }
    for i in 18..36 {
        windows[3][i] = libm::sinf(PI_36 * (i as f32 + 0.5));
    }

    windows
}

/// Cosine coefficients for half of a 12-point IMDCT.
pub fn mp3_imdct_half_cos_12() -> [[f32; 6]; 6] {
    const PI_24: f32 = PI / 24.0;

    let mut cos = [[0f32; 6]; 6];

    for (i, cos_i) in cos.iter_mut().enumerate() {
        for (k, cos_ik) in cos_i.iter_mut().enumerate() {
            let n = (2 * (i + 3) + (12 / 2) + 1) * (2 * k + 1);
            *cos_ik = libm::cosf(PI_24 * n as f32);
        }
    }

    cos
}

/// Alias reduction coefficients, CS and CA.
pub fn mp3_antialias_cs_ca() -> ([f32; 8], [f32; 8]) {
    const C: [f32; 8] = [-0.6, -0.535, -0.33, -0.185, -0.095, -0.041, -0.0142, -0.0037];

    let mut cs = [0f32; 8];
    let mut ca = [0f32; 8];

    for i in 0..8 {
        let sqrt = libm::sqrtf(1.0 + (C[i] * C[i]));
        cs[i] = 1.0 / sqrt;
        ca[i] = C[i] / sqrt;
    }

    (cs, ca)
}

/// MPEG2 intensity stereo (left, right) channel coefficients.
pub fn mp3_intensity_stereo_ratios_mpeg2() -> [[(f32, f32); 32]; 2] {
    let is_scale: [f32; 2] = [1.0 / libm::sqrtf(SQRT_2), FRAC_1_SQRT_2];

    let mut ratios = [[(0.0, 0.0); 32]; 2];

    for (i, is_pos) in (0..32).enumerate() {
        if is_pos & 1 != 0 {
            ratios[0][i] = (libm::powf(is_scale[0], (is_pos + 1) as f32 / 2.0), 1.0);
            ratios[1][i] = (libm::powf(is_scale[1], (is_pos + 1) as f32 / 2.0), 1.0);
        }
        else {
            ratios[0][i] = (1.0, libm::powf(is_scale[0], (is_pos) as f32 / 2.0));
            ratios[1][i] = (1.0, libm::powf(is_scale[1], (is_pos) as f32 / 2.0));
        }
    }

    ratios
}

/// MPEG1 intensity stereo (left, right) channel coefficients.
pub fn mp3_intensity_stereo_ratios_mpeg1() -> [(f32, f32); 7] {
    const PI_12: f32 = PI / 12.0;

    let mut ratios = [(0.0, 0.0); 7];

    for (is_pos, ratio) in ratios.iter_mut().enumerate() {
        let is_ratio = libm::tanf(PI_12 * is_pos as f32);
        *ratio = (is_ratio / (1.0 + is_ratio), 1.0 / (1.0 + is_ratio));
    }

    ratios[6] = (1.0, 0.0);

    ratios
}

pub fn gen_mp3() -> String {
    let mut out = String::new();

    write_header(&mut out, "MPEG audio decoder");

    let vis = "pub(crate)";
    let mp1 = Some("feature = \"mp1\"");
    let mp3 = Some("feature = \"mp3\"");

    write_f32_table(
        &mut out,
        vis,
        "LAYER1_FACTOR",
        "Layer 1 dequantization factors, [(2^nb) / ((2^nb) - 1)] * 2^(-nb + 1), for nb-bits samples\n\
         between 2..15, inclusive. See `layer1::dequantize`.",
        mp1,
        &mp1_factor(),
    );

    write_f32_table(
        &mut out,
        vis,
        "POW43",
        "Lookup table for computing x(i) = s(i)^(4/3) where s(i) is a decoded Huffman sample. The\n\
         value of s(i) is bound between 0..8207.",
        mp3,
        &mp3_pow43(),
    );

    write_f32_table(
        &mut out,
        vis,
        "POW2_TABLE",
        "Lookup table of y = 2^(0.25 * (x - 256)), centered at x = 256.",
        mp3,
        &mp3_pow2(),
    );

    // IMDCT windows.
    write_item_header(
        &mut out,
        "Hybrid synthesesis IMDCT window coefficients for: Long, Start, Short, and End block, in that\n\
         order.\n\
         \n\
         For long blocks:\n\
         \n\
         ```text\n\
         W[ 0..36] = sin(PI/36.0 * (i + 0.5))\n\
         ```\n\
         \n\
         For start blocks:\n\
         \n\
         ```text\n\
         W[ 0..18] = sin(PI/36.0 * (i + 0.5))\n\
         W[18..24] = 1.0\n\
         W[24..30] = sin(PI/12.0 * ((i - 18) - 0.5))\n\
         W[30..36] = 0.0\n\
         ```\n\
         \n\
         For short blocks (to be applied to each 12 sample window):\n\
         \n\
         ```text\n\
         W[ 0..12] = sin(PI/12.0 * (i + 0.5))\n\
         W[12..36] = 0.0\n\
         ```\n\
         \n\
         For end blocks:\n\
         \n\
         ```text\n\
         W[ 0..6 ] = 0.0\n\
         W[ 6..12] = sin(PI/12.0 * ((i - 6) + 0.5))\n\
         W[12..18] = 1.0\n\
         W[18..36] = sin(PI/36.0 * (i + 0.5))\n\
         ```",
        mp3,
    );
    writeln!(out, "{vis} static IMDCT_WINDOWS: [[f32; 36]; 4] = [").unwrap();
    for window in mp3_imdct_windows() {
        writeln!(out, "    [").unwrap();
        write_list(&mut out, &window, 6, 8, fmt_f32);
        writeln!(out, "    ],").unwrap();
    }
    writeln!(out, "];").unwrap();

    // IMDCT half cosine table.
    write_item_header(
        &mut out,
        "Lookup table of cosine coefficients for half of a 12-point IMDCT.\n\
         \n\
         This table is derived from the general expression:\n\
         \n\
         ```text\n\
         cos12[i][k] = cos(PI/24.0 * (2*i + 1 + N/2) * (2*k + 1))\n\
         ```\n\
         where:\n    `N=12`, `i=N/4..3N/4`, and `k=0..N/2`.",
        mp3,
    );
    writeln!(out, "{vis} static IMDCT_HALF_COS_12: [[f32; 6]; 6] = [").unwrap();
    for row in mp3_imdct_half_cos_12() {
        let items: Vec<String> = row.iter().map(fmt_f32).collect();
        writeln!(out, "    [{}],", items.join(", ")).unwrap();
    }
    writeln!(out, "];").unwrap();

    // Antialias coefficients.
    write_item_header(
        &mut out,
        "Pair of lookup tables, CS and CA, for alias reduction.\n\
         \n\
         As per ISO/IEC 11172-3, CS and CA are calculated as follows:\n\
         \n\
         ```text\n\
         cs[i] =  1.0 / sqrt(1.0 + c[i]^2)\n\
         ca[i] = c[i] / sqrt(1.0 + c[i]^2)\n\
         ```\n\
         \n\
         where:\n\
         ```text\n\
         c[i] = [ -0.6, -0.535, -0.33, -0.185, -0.095, -0.041, -0.0142, -0.0037 ]\n\
         ```",
        mp3,
    );
    let (cs, ca) = mp3_antialias_cs_ca();
    writeln!(out, "{vis} static ANTIALIAS_CS_CA: ([f32; 8], [f32; 8]) = (").unwrap();
    for table in [cs, ca] {
        writeln!(out, "    [").unwrap();
        write_list(&mut out, &table, 8, 8, fmt_f32);
        writeln!(out, "    ],").unwrap();
    }
    writeln!(out, ");").unwrap();

    // Intensity stereo ratios.
    write_item_header(
        &mut out,
        "(Left, right) channel coefficients for decoding intensity stereo in MPEG2 bitstreams.\n\
         \n\
         These coefficients are derived from section 2.4.3.2 of ISO/IEC 13818-3.\n\
         \n\
         As per the specification, for a given intensity position, is_pos (0 <= is_pos < 32), the\n\
         channel coefficients, k_l and k_r, may be calculated as per the table below:\n\
         \n\
         ```text\n\
         If...            | k_l                     | k_r\n\
         -----------------+-------------------------+-------------------\n\
         is_pos     == 0  | 1.0                     | 1.0\n\
         is_pos & 1 == 1  | i0 ^ [(is_pos + 1) / 2] | 1.0\n\
         is_pos & 1 == 0  | 1.0                     | i0 ^ (is_pos / 2)\n\
         ```\n\
         \n\
         The value of i0 is dependant on the least significant bit of scalefac_compress.\n\
         \n\
         ```text\n\
         scalefac_compress & 1 | i0\n\
         ----------------------+---------------------\n\
         0                     | 1 / sqrt(sqrt(2.0))\n\
         1                     | 1 / sqrt(2.0)\n\
         ```\n\
         \n\
         The first dimension of this table is indexed by scalefac_compress & 1 to select i0. The\n\
         second dimension is indexed by is_pos to obtain the channel coefficients. Note that\n\
         is_pos == 31 is considered an invalid position, but IS included in the table.",
        mp3,
    );
    writeln!(out, "{vis} static INTENSITY_STEREO_RATIOS_MPEG2: [[(f32, f32); 32]; 2] = [").unwrap();
    for ratios in mp3_intensity_stereo_ratios_mpeg2() {
        writeln!(out, "    [").unwrap();
        write_list(&mut out, &ratios, 4, 8, fmt_pair);
        writeln!(out, "    ],").unwrap();
    }
    writeln!(out, "];").unwrap();

    write_item_header(
        &mut out,
        "(Left, right) channel coeffcients for decoding intensity stereo in MPEG1 bitstreams.\n\
         \n\
         These coefficients are derived from section 2.4.3.4.9.3 of ISO/IEC 11172-3.\n\
         \n\
         As per the specification, for a given intensity position, is_pos (0 <= is_pos < 7), a ratio,\n\
         is_ratio, is calculated as follows:\n\
         \n\
         ```text\n\
         is_ratio = tan(is_pos * PI/12)\n\
         ```\n\
         \n\
         Then, the channel coefficients, k_l and k_r, are calculated as follows:\n\
         \n\
         ```text\n\
         k_l = is_ratio / (1 + is_ratio)\n\
         k_r =        1 / (1 + is_ratio)\n\
         ```\n\
         \n\
         This table is indexed by is_pos. Note that is_pos == 7 is invalid and is NOT included in the\n\
         table.",
        mp3,
    );
    writeln!(out, "{vis} static INTENSITY_STEREO_RATIOS_MPEG1: [(f32, f32); 7] = [").unwrap();
    write_list(&mut out, &mp3_intensity_stereo_ratios_mpeg1(), 4, 4, fmt_pair);
    writeln!(out, "];").unwrap();

    out
}
