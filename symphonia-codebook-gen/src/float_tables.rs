//! Floating-point lookup tables (dequantization, windows, stereo ratios, etc.).
//!
//! Every table is computed with `libm` using the same sequence of operations the decoders
//! previously used at runtime on `no_std` targets, so that the stored values are bit-identical.
//! Values are written using Rust's shortest round-trip formatting, which parses back to the exact
//! same `f32`.

// Justification: The table generators mirror the decoders' original loops.
#![allow(clippy::needless_range_loop)]

use core::f32::consts::{FRAC_1_SQRT_2, PI, SQRT_2};
use core::fmt::Write;

use crate::LICENSE;

/// Write the module header for a generated floating-point tables file.
fn write_header(out: &mut String, desc: &str) {
    writeln!(out, "{LICENSE}").unwrap();
    writeln!(out, "//! Pre-generated floating-point lookup tables for the {desc}.").unwrap();
    writeln!(out, "//!").unwrap();
    writeln!(
        out,
        "//! These tables are stored as `static`s so that they are placed in read-only memory \
         instead of\n\
         //! being computed on the heap at runtime.\n\
         //!\n\
         //! Generated by `symphonia-codebook-gen`. Do not edit by hand."
    )
    .unwrap();
    writeln!(out).unwrap();
    writeln!(
        out,
        "// Some computed values happen to equal mathematical constants (e.g., sqrt(2))."
    )
    .unwrap();
    writeln!(out, "#![allow(clippy::approx_constant)]").unwrap();
}

/// Format a list of values, `per_line` values per line, each line indented by `indent` spaces.
fn write_list<T>(
    out: &mut String,
    values: &[T],
    per_line: usize,
    indent: usize,
    f: fn(&T) -> String,
) {
    for chunk in values.chunks(per_line) {
        let items: Vec<String> = chunk.iter().map(f).collect();
        writeln!(out, "{:indent$}{},", "", items.join(", ")).unwrap();
    }
}

fn fmt_f32(v: &f32) -> String {
    format!("{v:?}")
}

fn fmt_pair(v: &(f32, f32)) -> String {
    format!("({:?}, {:?})", v.0, v.1)
}

/// Write the doc comment and attributes of a table.
fn write_item_header(out: &mut String, doc: &str, cfg: Option<&str>) {
    writeln!(out).unwrap();
    for line in doc.lines() {
        if line.is_empty() {
            writeln!(out, "///").unwrap();
        }
        else {
            writeln!(out, "/// {line}").unwrap();
        }
    }
    if let Some(cfg) = cfg {
        writeln!(out, "#[cfg({cfg})]").unwrap();
    }
    writeln!(out, "#[rustfmt::skip]").unwrap();
}

/// Write a 1-dimensional `f32` table.
fn write_f32_table(
    out: &mut String,
    vis: &str,
    name: &str,
    doc: &str,
    cfg: Option<&str>,
    values: &[f32],
) {
    write_item_header(out, doc, cfg);
    writeln!(out, "{vis} static {name}: [f32; {}] = [", values.len()).unwrap();
    write_list(out, values, 8, 4, fmt_f32);
    writeln!(out, "];").unwrap();
}

// AAC
