/// y = x^(4/3), for x in 0..8192.
pub fn aac_pow43() -> Vec<f32> {
    (0..8192).map(|i| libm::powf(i as f32, 4.0 / 3.0)).collect()
}

/// y = 2^(0.25 * (x - 156)), for x in 0..256.
pub fn aac_normal_scf() -> Vec<f32> {
    const NORMAL_SCALE_MIN: i16 = -100;
    (0..256).map(|i| libm::powf(2.0, 0.25 * f32::from(i as i16 - 56 + NORMAL_SCALE_MIN))).collect()
}

/// y = 0.5^(0.25 * (x - 155)), for x in 0..256.
pub fn aac_intensity_scf() -> Vec<f32> {
    const INTENSITY_SCALE_MIN: i16 = -155;
    (0..256).map(|i| libm::powf(0.5, 0.25 * f32::from(i as i16 + INTENSITY_SCALE_MIN))).collect()
}

/// Half of a sine window of length `2 * size`.
pub fn aac_sine_window(size: usize) -> Vec<f32> {
    let param = PI / ((2 * size) as f32);
    (0..size).map(|n| libm::sinf(((n as f32) + 0.5) * param) * 1.0).collect()
}

/// Half of a Kaiser-Bessel derived window of length `2 * size`.
pub fn aac_kbd_window(alpha: f32, size: usize) -> Vec<f32> {
    fn bessel_i0(inval: f64) -> f64 {
        let mut val: f64 = 1.0;
        for n in (1..64).rev() {
            val *= inval / f64::from(n * n);
            val += 1.0;
        }
        val
    }

    let dlen = size as f32;
    let alpha2 = f64::from((alpha * PI / dlen) * (alpha * PI / dlen));

    let mut kb: Vec<f64> = Vec::with_capacity(size);
    let mut sum = 0.0;
    for n in 0..size {
        let b = bessel_i0(((n * (size - n)) as f64) * alpha2);
        sum += b;
        kb.push(sum);
    }
    sum += 1.0;

    kb.iter().map(|&kb| libm::sqrt(kb / sum) as f32).collect()
}

/// IMDCT twiddle factors as computed by `Imdct::new_scaled(n, scale)`, as (re, im) pairs.
pub fn imdct_twiddle(n: usize, scale: f64) -> Vec<(f32, f32)> {
    let n2 = n / 2;

    let alpha = 1.0 / 8.0 + if scale.is_sign_positive() { 0.0 } else { n2 as f32 };
    let pi_n = PI / n as f32;
    let sqrt_scale = libm::sqrtf((scale as f32).abs());

    (0..n2)
        .map(|k| {
            let theta = pi_n * (alpha + k as f32);
            (sqrt_scale * libm::cosf(theta), sqrt_scale * libm::sinf(theta))
        })
        .collect()
}

/// Write IMDCT twiddle factors as a `Complex<f32>` table.
fn write_twiddle_table(out: &mut String, vis: &str, name: &str, doc: &str, twiddle: &[(f32, f32)]) {
    write_item_header(out, doc, None);
    writeln!(out, "{vis} static {name}: [Complex<f32>; {}] = [", twiddle.len()).unwrap();
    write_list(out, twiddle, 4, 4, |&(re, im)| format!("c({re:?}, {im:?})"));
    writeln!(out, "];").unwrap();
}

pub fn gen_aac() -> String {
    let mut out = String::new();

    write_header(&mut out, "AAC decoder");

    writeln!(out).unwrap();
    writeln!(out, "use symphonia_core::dsp::complex::Complex;").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "/// A complex value.").unwrap();
    writeln!(out, "const fn c(re: f32, im: f32) -> Complex<f32> {{").unwrap();
    writeln!(out, "    Complex::new(re, im)").unwrap();
    writeln!(out, "}}").unwrap();

    let vis = "pub(super)";

    write_f32_table(
        &mut out,
        vis,
        "POW43_TABLE",
        "Pre-computed table of y = x^(4/3).",
        None,
        &aac_pow43(),
    );

    write_f32_table(
        &mut out,
        vis,
        "NORMAL_SCF_TABLE",
        "Pre-computed table of y = 2^(0.25 * (x - 156)) for decoding scale factors for normal bands.\n\
         This table is indexed relative to -100, the minimum encoded scale factor value for normal\n\
         bands. Therefore, an input of 0 corresponds to -100.",
        None,
        &aac_normal_scf(),
    );

    write_f32_table(
        &mut out,
        vis,
        "INTENSITY_SCF_TABLE",
        "Pre-computed table of y = 0.5^(0.25 * (x - 155)) for decoding scale factors for intensity\n\
         coded bands. This table is indexed relative to -155, the minimum encoded scale factor value\n\
         for intensity coded bands. Therefore, an input of 0 corresponds to -155.",
        None,
        &aac_intensity_scf(),
    );

    write_f32_table(
        &mut out,
        vis,
        "KBD_LONG_WINDOW",
        "The first half of the Kaiser-Bessel derived (alpha = 4) window for long blocks.",
        None,
        &aac_kbd_window(4.0, 1024),
    );

    write_f32_table(
        &mut out,
        vis,
        "KBD_SHORT_WINDOW",
        "The first half of the Kaiser-Bessel derived (alpha = 6) window for short blocks.",
        None,
        &aac_kbd_window(6.0, 128),
    );

    write_f32_table(
        &mut out,
        vis,
        "SINE_LONG_WINDOW",
        "The first half of the sine window for long blocks.",
        None,
        &aac_sine_window(1024),
    );

    write_f32_table(
        &mut out,
        vis,
        "SINE_SHORT_WINDOW",
        "The first half of the sine window for short blocks.",
        None,
        &aac_sine_window(128),
    );

    write_twiddle_table(
        &mut out,
        vis,
        "IMDCT_LONG_TWIDDLE",
        "Twiddle factors for the 1024-point IMDCT with a scale of 1/2048.",
        &imdct_twiddle(1024, 1.0 / 2048.0),
    );

    write_twiddle_table(
        &mut out,
        vis,
        "IMDCT_SHORT_TWIDDLE",
        "Twiddle factors for the 128-point IMDCT with a scale of 1/256.",
        &imdct_twiddle(128, 1.0 / 256.0),
    );

    out
}

