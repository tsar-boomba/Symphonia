//! Generates the pre-built lookup tables used by the AAC and MP3 decoders.
//!
//! The decoders store their Huffman codebooks and floating-point tables as `static` tables so
//! that they are placed in read-only memory instead of being built on the heap at runtime. This
//! tool builds the codebooks from the specification's codewords with `CodebookBuilder`, computes
//! the floating-point tables, and overwrites:
//!
//!  - `symphonia-codec-aac/src/aac/codebooks/tables.rs`
//!  - `symphonia-codec-aac/src/aac/tables.rs`
//!  - `symphonia-bundle-mp3/src/layer3/codebooks/tables.rs`
//!  - `symphonia-bundle-mp3/src/tables.rs`
//!
//! To change the lookup table size/speed trade-off, edit `AAC_BITS_PER_READ` or
//! `MP3_BITS_PER_READ`, then run `cargo run -p symphonia-codebook-gen`.

// Writing to a `String` cannot fail, and the specification tables are known to be valid.
#![allow(clippy::unwrap_used)]

use core::fmt::Write;
use std::path::Path;

use critical_section as _;
use symphonia_core::io::vlc::{BitOrder, Codebook, CodebookBuilder, CodebookEntry, Entry};

mod aac;
mod float_tables;
mod mp3;

/// The number of bits read per lookup for the AAC codebooks.
const AAC_BITS_PER_READ: u8 = 5;

/// The number of bits read per lookup for the MP3 codebooks.
const MP3_BITS_PER_READ: u8 = 5;

const LICENSE: &str = "\
// Symphonia
// Copyright (c) 2019-2026 The Project Symphonia Developers.
//
// This Source Code Form is subject to the terms of the Mozilla Public
// License, v. 2.0. If a copy of the MPL was not distributed with this
// file, You can obtain one at https://mozilla.org/MPL/2.0/.
";

const ENTRY_HELPERS: &str = "
/// A jump entry.
const fn j<E: CodebookEntry<IndexType = u16>>(index: u16) -> Entry<E> {
    Entry::Jump { index }
}

/// A value entry.
const fn v<E: CodebookEntry>(value: E::ValueType, code_len: u8) -> Entry<E> {
    match NonZero::new(code_len) {
        Some(code_len) => Entry::Value { value, code_len },
        None => panic!(\"zero length codeword\"),
    }
}
";

fn main() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");

    let files = [
        ("symphonia-codec-aac/src/aac/codebooks/tables.rs", gen_aac()),
        ("symphonia-codec-aac/src/aac/tables.rs", float_tables::gen_aac()),
        ("symphonia-bundle-mp3/src/layer3/codebooks/tables.rs", gen_mp3()),
        ("symphonia-bundle-mp3/src/tables.rs", float_tables::gen_mp3()),
    ];

    for (path, contents) in files {
        let path = root.join(path);
        std::fs::write(&path, contents).expect("write tables");
        println!("wrote {}", path.display());
    }
}

/// Build a codebook with `CodebookBuilder`.
fn make_codebook<E: CodebookEntry>(
    codes: &[u32],
    lens: &[u8],
    values: &[E::ValueType],
    bits_per_read: u8,
) -> Codebook<E> {
    let mut builder = CodebookBuilder::new(BitOrder::Verbatim);
    builder.bits_per_read(bits_per_read);
    builder.make(codes, lens, values).expect("valid static codebook data")
}

/// Write the module header shared by all generated files.
fn write_header(out: &mut String, desc: &str, bits_per_read: u8, imports: &str) {
    writeln!(out, "{LICENSE}").unwrap();
    writeln!(out, "//! Pre-generated lookup tables for the {desc}.").unwrap();
    writeln!(out, "//!").unwrap();
    writeln!(
        out,
        "//! These tables are the output of `CodebookBuilder` (`BitOrder::Verbatim`, \
         `bits_per_read({bits_per_read})`)"
    )
    .unwrap();
    writeln!(
        out,
        "//! for the specification's codewords. They are stored as `static`s so that they are \
         placed in\n\
         //! read-only memory instead of being built on the heap at runtime.\n\
         //!\n\
         //! Generated by `symphonia-codebook-gen`. Do not edit by hand."
    )
    .unwrap();
    writeln!(out).unwrap();
    writeln!(out, "use core::num::NonZero;").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "use symphonia_core::io::vlc::{{{imports}}};").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "use super::StaticCodebook;").unwrap();
    write!(out, "{ENTRY_HELPERS}").unwrap();
}

/// Write a codebook's entry table as a `static`. Returns the maximum codeword length and number of
/// bits per read of the codebook.
fn write_entries<E: CodebookEntry>(
    out: &mut String,
    name: &str,
    entry_type: &str,
    codebook: &Codebook<E>,
) -> (u32, u32)
where
    E::IndexType: Into<u32>,
    E::ValueType: Into<u32>,
{
    let (table, max_code_len, bits_per_read) = codebook.as_parts();

    writeln!(out, "#[rustfmt::skip]").unwrap();
    writeln!(out, "static {name}: [Entry<{entry_type}>; {}] = [", table.len()).unwrap();

    for chunk in table.chunks(8) {
        let items: Vec<String> = chunk
            .iter()
            .map(|entry| match *entry {
                Entry::Jump { index } => format!("j({})", index.into()),
                Entry::Value { value, code_len } => format!("v({}, {})", value.into(), code_len),
            })
            .collect();

        writeln!(out, "    {},", items.join(", ")).unwrap();
    }

    writeln!(out, "];").unwrap();
    writeln!(out).unwrap();

    (max_code_len, bits_per_read)
}

/// Write a list of values as a `static`, `per_line` values per line.
fn write_values<T>(
    out: &mut String,
    name: &str,
    ty: &str,
    values: &[T],
    per_line: usize,
    f: fn(&T) -> String,
) {
    writeln!(out, "#[rustfmt::skip]").unwrap();
    writeln!(out, "pub(super) static {name}: [{ty}; {}] = [", values.len()).unwrap();

    for chunk in values.chunks(per_line) {
        let items: Vec<String> = chunk.iter().map(f).collect();
        writeln!(out, "    {},", items.join(", ")).unwrap();
    }

    writeln!(out, "];").unwrap();
}

/// Inverse quantization.
fn iquant(val: usize) -> f32 {
    // Use libm to match the decoders' `no_std` floating-point implementation.
    libm::powf(val as f32, 4.0 / 3.0)
}

fn signed_pair<const MOD: usize>(cw: usize) -> (f32, f32) {
    let modulo_2 = MOD >> 1;

    let a = cw / MOD;
    let b = cw % MOD;

    let x = if modulo_2 > a { -iquant(modulo_2 - a) } else { iquant(a - modulo_2) };
    let y = if modulo_2 > b { -iquant(modulo_2 - b) } else { iquant(b - modulo_2) };

    (x, y)
}

fn unsigned_pair<const MOD: usize>(cw: usize) -> (f32, f32) {
    (iquant(cw / MOD), iquant(cw % MOD))
}

fn escape_pair<const MOD: usize>(cw: usize) -> (u16, u16) {
    ((cw / MOD) as u16, (cw % MOD) as u16)
}

fn gen_aac() -> String {
    use symphonia_core::io::vlc::{Entry8x16, Entry16x16};

    let mut out = String::new();

    write_header(
        &mut out,
        "AAC spectral and scale factor Huffman\n//! codebooks (ISO/IEC 14496-3)",
        AAC_BITS_PER_READ,
        "Codebook, CodebookEntry, Entry, Entry8x16, Entry16x16",
    );

    writeln!(out).unwrap();
    writeln!(out, "/// A dequantized spectral pair, given as the bit patterns of each value.")
        .unwrap();
    writeln!(out, "const fn p(a: u32, b: u32) -> (f32, f32) {{").unwrap();
    writeln!(out, "    (f32::from_bits(a), f32::from_bits(b))").unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    // Spectral codebooks. The codebook returns the index of the decoded codeword.
    let mut spectrum = Vec::new();

    for (i, table) in aac::SPECTRUM_TABLES.iter().enumerate() {
        let indicies: Vec<u16> = (0..table.codes.len() as u16).collect();

        let codebook: Codebook<Entry16x16> =
            make_codebook(table.codes, table.lens, &indicies, AAC_BITS_PER_READ);

        let name = format!("SPECTRUM{}", i + 1);
        let parts = write_entries(&mut out, &name, "Entry16x16", &codebook);

        spectrum.push((name, parts));
    }

    for (name, (max_code_len, bits_per_read)) in &spectrum {
        writeln!(out, "pub(super) const {name}_CODEBOOK: StaticCodebook<Entry16x16> =").unwrap();
        writeln!(out, "    Codebook::from_table(&{name}, {max_code_len}, {bits_per_read});")
            .unwrap();
    }
    writeln!(out).unwrap();

    // Scale factor codebook.
    let values: Vec<u8> = (0..aac::SCF_CODEBOOK_CODES.len() as u8).collect();

    let codebook: Codebook<Entry8x16> = make_codebook(
        &aac::SCF_CODEBOOK_CODES,
        &aac::SCF_CODEBOOK_LENS,
        &values,
        AAC_BITS_PER_READ,
    );

    let (max_code_len, bits_per_read) = write_entries(&mut out, "SCF", "Entry8x16", &codebook);

    writeln!(
        out,
        "pub(super) const SCF_CODEBOOK: StaticCodebook<Entry8x16> = \
         Codebook::from_table(&SCF, {max_code_len}, {bits_per_read});"
    )
    .unwrap();
    writeln!(out).unwrap();

    // Dequantized values for the spectral pair codebooks 5 through 10.
    let pairs: [fn(usize) -> (f32, f32); 6] = [
        signed_pair::<9>,
        signed_pair::<9>,
        unsigned_pair::<8>,
        unsigned_pair::<8>,
        unsigned_pair::<13>,
        unsigned_pair::<13>,
    ];

    for (i, f) in pairs.iter().enumerate() {
        let values: Vec<(f32, f32)> = (0..aac::SPECTRUM_TABLES[i + 4].codes.len()).map(f).collect();

        write_values(
            &mut out,
            &format!("SPECTRUM{}_VALUES", i + 5),
            "(f32, f32)",
            &values,
            4,
            |(a, b)| format!("p({:#010x}, {:#010x})", a.to_bits(), b.to_bits()),
        );
        writeln!(out).unwrap();
    }

    // Values for the escape codebook (11).
    let values: Vec<(u16, u16)> =
        (0..aac::SPECTRUM_TABLES[10].codes.len()).map(escape_pair::<17>).collect();

    write_values(&mut out, "SPECTRUM11_VALUES", "(u16, u16)", &values, 8, |(a, b)| {
        format!("({a}, {b})")
    });

    out
}

fn gen_mp3() -> String {
    use symphonia_core::io::vlc::Entry16x16;

    fn gen_value(i: u16, wrap: u16) -> u16 {
        ((i / wrap) << 4) | (i % wrap)
    }

    fn make(codes: &[u32], lens: &[u8], wrap: u16) -> Codebook<Entry16x16> {
        let values: Vec<u16> = (0..codes.len() as u16).map(|i| gen_value(i, wrap)).collect();
        make_codebook(codes, lens, &values, MP3_BITS_PER_READ)
    }

    let mut out = String::new();

    write_header(
        &mut out,
        "MPEG-1/2 Layer III Huffman codebooks (ISO/IEC 11172-3)",
        MP3_BITS_PER_READ,
        "Codebook, CodebookEntry, Entry, Entry16x16",
    );
    writeln!(out).unwrap();

    let mut tables = Vec::new();

    for (i, table) in mp3::MPEG_TABLES.iter().enumerate() {
        let name = format!("TABLE{i}");
        let codebook = make(table.codes, table.lens, table.wrap);
        tables.push((name.clone(), write_entries(&mut out, &name, "Entry16x16", &codebook)));
    }

    let mut quads = Vec::new();

    for (table, suffix) in mp3::MPEG_QUADS_TABLES.iter().zip(["A", "B"]) {
        let name = format!("QUADS_TABLE{suffix}");
        let codebook = make(table.codes, table.lens, table.wrap);
        quads.push((name.clone(), write_entries(&mut out, &name, "Entry16x16", &codebook)));
    }

    fn write_array(out: &mut String, name: &str, list: &[(String, (u32, u32))]) {
        writeln!(out, "pub static {name}: [StaticCodebook<Entry16x16>; {}] = [", list.len())
            .unwrap();
        for (table, (max_code_len, bits_per_read)) in list {
            writeln!(out, "    Codebook::from_table(&{table}, {max_code_len}, {bits_per_read}),")
                .unwrap();
        }
        writeln!(out, "];").unwrap();
    }

    write_array(&mut out, "CODEBOOK_TABLES", &tables);
    writeln!(out).unwrap();
    write_array(&mut out, "QUADS_CODEBOOK_TABLE", &quads);

    out
}
