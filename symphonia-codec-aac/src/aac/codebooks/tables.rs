//! Pre-generated lookup tables for the AAC spectral and scale factor Huffman
//! codebooks (ISO/IEC 14496-3).
//!
//! These tables are the output of `CodebookBuilder` (`BitOrder::Verbatim`, `bits_per_read(5)`)
//! for the specification's codewords. They are stored as `static`s so that they are placed in
//! read-only memory instead of being built on the heap at runtime.
//!
//! Generated by `symphonia-codebook-gen`. Do not edit by hand.

use core::num::NonZero;

use symphonia_core::io::vlc::{Codebook, CodebookEntry, Entry, Entry8x16, Entry16x16};

use super::StaticCodebook;

/// A jump entry.
const fn j<E: CodebookEntry<IndexType = u16>>(index: u16) -> Entry<E> {
    Entry::Jump { index }
}

/// A value entry.
const fn v<E: CodebookEntry>(value: E::ValueType, code_len: u8) -> Entry<E> {
    match NonZero::new(code_len) {
        Some(code_len) => Entry::Value { value, code_len },
        None => panic!("zero length codeword"),
    }
}

/// A dequantized spectral pair, given as the bit patterns of each value.
const fn p(a: u32, b: u32) -> (f32, f32) {
    (f32::from_bits(a), f32::from_bits(b))
}

